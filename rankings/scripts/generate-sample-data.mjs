// Writes placeholder pictures (public/samples/) and supabase/seed.sql with sample contestants and
// categories for local development. Run with `node scripts/generate-sample-data.mjs`.
import { mkdirSync, rmSync, writeFileSync } from "node:fs";

const categories = [
  {
    name: "Pizza toppings",
    description: "What belongs on a pizza?",
    contestants: ["Pepperoni", "Mushroom", "Pineapple", "Olive", "Onion", "Sausage", "Bacon", "Jalapeño", "Basil", "Ham", "Green pepper", "Anchovy"],
  },
  {
    name: "Fruits",
    description: "Nature's candy.",
    contestants: ["Apple", "Banana", "Mango", "Strawberry", "Pineapple", "Grape", "Watermelon", "Peach", "Cherry", "Kiwi"],
  },
  {
    name: "Dog breeds",
    description: "Every dog is a good dog, but which is best?",
    contestants: ["Corgi", "Shiba Inu", "Golden retriever", "Poodle", "Beagle", "Husky", "Dachshund", "Pug"],
  },
  {
    name: "Primary colors",
    description: "Too few for a tournament, until someone adds more.",
    contestants: ["Red", "Blue", "Yellow"],
  },
];

const slug = (name) =>
  name.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

function hue(name) {
  let h = 0;
  for (const ch of name) h = (h * 31 + ch.codePointAt(0)) % 360;
  return h;
}

function svg(name, size) {
  const h = hue(name);
  const initials = name.split(/\s+/).map((w) => w[0]).join("").slice(0, 2).toUpperCase();
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 512 512">
<rect width="512" height="512" fill="hsl(${h} 70% 55%)"/>
<circle cx="256" cy="220" r="130" fill="hsl(${(h + 40) % 360} 80% 85%)"/>
<text x="256" y="268" font-family="system-ui, sans-serif" font-size="130" font-weight="700" text-anchor="middle" fill="hsl(${h} 60% 25%)">${initials}</text>
<text x="256" y="440" font-family="system-ui, sans-serif" font-size="48" font-weight="600" text-anchor="middle" fill="white">${name}</text>
</svg>
`;
}

const dir = new URL("../public/samples/", import.meta.url);
rmSync(dir, { recursive: true, force: true });
mkdirSync(dir, { recursive: true });

const names = [...new Set(categories.flatMap((c) => c.contestants))];
for (const name of names) {
  writeFileSync(new URL(`${slug(name)}-512.svg`, dir), svg(name, 512));
  writeFileSync(new URL(`${slug(name)}-128.svg`, dir), svg(name, 128));
}

const q = (s) => `'${s.replaceAll("'", "''")}'`;
const id = (kind, name) => `md5(${q(`${kind}:${name}`)})::uuid`;

const sql = [
  "-- Sample catalog for local development. Generated by scripts/generate-sample-data.mjs; do not edit by hand.",
  "",
  "insert into public.contestants (id, name, picture_512_url, picture_128_url) values",
  names
    .map((n) => `  (${id("contestant", n)}, ${q(n)}, ${q(`/samples/${slug(n)}-512.svg`)}, ${q(`/samples/${slug(n)}-128.svg`)})`)
    .join(",\n") + ";",
  "",
  "insert into public.categories (id, name, description) values",
  categories.map((c) => `  (${id("category", c.name)}, ${q(c.name)}, ${q(c.description)})`).join(",\n") + ";",
  "",
  "insert into public.category_memberships (category_id, contestant_id) values",
  categories
    .flatMap((c) => c.contestants.map((n) => `  (${id("category", c.name)}, ${id("contestant", n)})`))
    .join(",\n") + ";",
  "",
];
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql.join("\n"));
console.log(`Wrote ${names.length} sample contestants in ${categories.length} categories`);
